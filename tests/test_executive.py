def _run_until_terminal(eng, identity, task_id, cap=200):
    guard = 0
    while guard < cap:
        eng.process_ready(identity)
        t = eng.get_task(identity, task_id)
        if t.status.value in ("completed", "failed", "cancelled"):
            return t
        guard += 1
    return eng.get_task(identity, task_id)


def _cleanup_generated(cap_id):
    root = os.path.join(os.path.dirname(__file__), "..")
    for rel in (
        f"core/capabilities/{cap_id}",
        f"registry/capabilities/{cap_id}",
    ):
        p = os.path.normpath(os.path.join(root, rel))
        if os.path.isdir(p):
            shutil.rmtree(p, ignore_errors=True)
    index = os.path.normpath(os.path.join(root, "registry/capabilities/index.json"))
    if os.path.exists(index):
        import json
        with open(index) as f:
            data = json.load(f)
        caps = data.get("capabilities", [])
        data["capabilities"] = [c for c in caps if c.get("id") != cap_id]
        with open(index, "w") as f:
            json.dump(data, f, indent=2)
    root_index = os.path.normpath(os.path.join(root, "registry/index.json"))
    if os.path.exists(root_index):
        import json
        with open(root_index) as f:
            data = json.load(f)
        caps = data.get("capabilities", [])
        data["capabilities"] = [c for c in caps if c.get("id") != cap_id]
        with open(root_index, "w") as f:
            json.dump(data, f, indent=2)


