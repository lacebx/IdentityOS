def test_scheduler_runs_tasks_in_background(storage, registry, fresh_cap):
    eng = ExecutiveRuntime(storage=storage, capability_registry=registry, autostart=True)
    t = eng.start_task(
        f"create a {fresh_cap} capability and install it",
        "tester", original_request=f"create a {fresh_cap} capability and install it",
    )
    assert eng.scheduler._thread is not None
    deadline = time.time() + 20
    final = None
    while time.time() < deadline:
        final = eng.get_task("tester", t.task_id)
        if final.status.value in ("completed", "failed", "cancelled"):
            break
        time.sleep(0.2)
    assert final is not None and final.status.value in ("completed", "failed", "cancelled")
    eng.shutdown()


