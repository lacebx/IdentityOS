def test_registry_reload_binds_storage(tmp_path):
    """Capabilities re-loaded from storage must have storage re-bound so skill
    calls reach the live engine (fixes 'NoneType' object has no attribute
    'load' when the LLM calls executive.current_task in a fresh process)."""
    from core.capabilities.registry import CapabilityRegistry
    storage = JSONFileBackend(root_dir=str(tmp_path))
    reg = CapabilityRegistry(storage)
    reg.install("tester", "executive")

    # Simulate a fresh process: new registry over the same storage.
    reg2 = CapabilityRegistry(storage)
    cap = reg2.get("tester", "executive")
    assert cap is not None
    assert cap._storage is not None, "install() must re-bind storage on reload"

    r = cap.call("executive.history", identity_id="tester")
    assert r.success, r.error
