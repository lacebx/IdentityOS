def test_delegate_to_executive_skips_status_questions_and_duplicates(tmp_path):
    """Prometheus delegation must not re-commit on questions, and must not
    re-queue a capability that already completed."""
    from core.executive.workflow import build_acquisition_plan
    from core.prometheus.models import CapabilityNeed, EvolutionResult
    from core.prometheus.pipeline import EvolutionPipeline
    from runtime.persistence import JSONFileBackend

    class FakeRuntime:
        def __init__(self, root):
            self.executive = ExecutiveRuntime(storage=JSONFileBackend(root_dir=root))

    rt = FakeRuntime(str(tmp_path))
    rt.executive.scheduler.start = lambda: None  # don't race the test
    pipeline = EvolutionPipeline()
    storage = JSONFileBackend(root_dir=str(tmp_path))

    def make_need(cap, request):
        return CapabilityNeed(
            skill_keywords=[cap],
            confidence=0.9,
            source="user_input",
            original_request=request,
            suggested_capability_ids=[cap],
        )

    # 1) A status question must NOT create a task.
    res = pipeline._delegate_to_executive(
        make_need("speech", "did you finish creating the speech capability?"),
        "tester", rt, storage, None,
    )
    assert res is not None and not res.acquired
    assert rt.executive.active_tasks("tester") == []

    # 2) A real acquisition creates a task.
    res = pipeline._delegate_to_executive(
        make_need("exec_test_q", "create a exec_test_q capability and install it"),
        "tester", rt, storage, None,
    )
    assert res is not None
    assert len(rt.executive.active_tasks("tester")) == 1

    # 3) Re-delegating the same capability is idempotent (active task exists).
    res = pipeline._delegate_to_executive(
        make_need("exec_test_q", "create a exec_test_q capability and install it"),
        "tester", rt, storage, None,
    )
    assert not res.acquired and "already active" in (res.acquisition_record.error or "")

    # 4) A completed capability must not be re-queued.  Finish the step-2
    #    task (running -> completed) so only the terminal check applies.
    from core.executive.models import TaskStatus
    from core.executive.state import can_transition, transition as _transition
    _active = rt.executive.active_tasks("tester")[0]
    if can_transition(_active.status, TaskStatus.RUNNING):
        _transition(_active, TaskStatus.RUNNING)
        rt.executive.store.save(_active)
    rt.executive.complete_task("tester", _active.task_id)
    task = rt.executive.start_task(
        identity_id="tester",
        goal="create a exec_test_q capability",
        capability_id="exec_test_q",
        steps=build_acquisition_plan("exec_test_q"),
    )
    _transition(task, TaskStatus.RUNNING)
    rt.executive.store.save(task)
    rt.executive.complete_task("tester", task.task_id)
    res = pipeline._delegate_to_executive(
        make_need("exec_test_q", "create a exec_test_q capability and install it"),
        "tester", rt, storage, None,
    )
