def build_aster_config(
    project_root: str | Path,
    *,
    sender_email: str = ASTER_EMAIL,
    sender_name: str = ASTER_NAME,
    candidate_sources: Optional[Iterable[CandidateSource]] = None,
    required_skills: Optional[list[str]] = None,
    search_fn: Any = None,
    interop: bool = True,
) -> OperatorConfig:
    sources: list[CandidateSource] = list(candidate_sources or [])
    if search_fn is not None:
        sources.append(
            SearchCandidateSource(
                search_fn,
                query_template="{category} program or organization related to: {need}",
            )
        )
    if required_skills is None:
        skills = ["web.fetch", "web.search", "email.send"]
        if interop:
            from .skill_acquisition import build_interop_required_skills

            skills.extend(build_interop_required_skills())
    else:
        skills = required_skills
    return OperatorConfig(
        identity_id=ASTER_ID,
        project_root=str(project_root),
        project_name="IdentityOS",
        sender_name=sender_name,
        sender_email=sender_email,
        signature=ASTER_SIGNATURE,
        transparency=ASTER_TRANSPARENCY,
        purpose="IdentityOS resource & collaboration outreach",
        need_rules=default_need_rules(),
        candidate_sources=sources,
        required_skills=skills,
        pursue_threshold=0.5,
        hold_threshold=0.38,
    )


def build_aster_engine(
    storage: Any,
    *,
    project_root: str | Path = ".",
    transport: Any = None,
    adapter: Any = None,
    identity: Any = None,
    capability_registry: Any = None,
    acquisition: Any = None,
    candidate_sources: Optional[Iterable[CandidateSource]] = None,
    search_fn: Any = None,
    required_skills: Optional[list[str]] = None,
    sender_email: str = ASTER_EMAIL,
    secret_store: Any = None,
    surfaces: Iterable[Any] = (),
    presence: Any = None,
    register: bool = True,
) -> OperationsEngine:
    config = build_aster_config(
        project_root,
        sender_email=sender_email,
        candidate_sources=candidate_sources,
        required_skills=required_skills,
        search_fn=search_fn,
    )
    if presence is None:
        from .presence import PresenceStore

        presence = PresenceStore(
            storage,
            config.identity_id,
            display_name=ASTER_NAME,
            objective=config.purpose,
            scrub_fn=(secret_store.scrub if secret_store else None),
        )
    engine = OperationsEngine(
        storage,
        config,
        transport=transport,
        adapter=adapter,
        identity=identity,
        capability_registry=capability_registry,
        acquisition=acquisition,
        search_fn=search_fn,
        secret_store=secret_store,
        surfaces=surfaces,
        presence=presence,
        communication_identity=aster_communication_identity(),
    )
    if register:
        register_engine(engine)
    return engine


